import { Schema, model, models, Types } from 'mongoose';

/*
|--------------------------------------------------------------------------
| Session Schema
|--------------------------------------------------------------------------
| One employee can have:
|
| AM:
|   Login -> Break(s) -> Logout
|
| PM:
|   Login -> Break(s) -> Logout
|
| Each session is independent.
|--------------------------------------------------------------------------
*/

const SessionSchema = new Schema(
  {
    /*
    |--------------------------------------------------------------------------
    | Check In
    |--------------------------------------------------------------------------
    */

    checkIn: {
      type: Date,
      default: null,
    },

    /*
    |--------------------------------------------------------------------------
    | Check Out
    |--------------------------------------------------------------------------
    */

    checkOut: {
      type: Date,
      default: null,
    },

    /*
    |--------------------------------------------------------------------------
    | Current Status
    |--------------------------------------------------------------------------
    */

    currentStatus: {
      type: String,
      enum: ['Working', 'On Break', 'Checked Out'],
      default: 'Checked Out',
    },

    /*
    |--------------------------------------------------------------------------
    | Last Activity
    |--------------------------------------------------------------------------
    */

    lastActivityAt: {
      type: Date,
      default: null,
    },

    /*
    |--------------------------------------------------------------------------
    | Working Minutes
    |--------------------------------------------------------------------------
    | Actual working time for this session.
    |--------------------------------------------------------------------------
    */

    workingMinutes: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Break Minutes
    |--------------------------------------------------------------------------
    | Total breaks for this session.
    |--------------------------------------------------------------------------
    */

    breakMinutes: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Automatic Logout
    |--------------------------------------------------------------------------
    */

    autoLoggedOut: {
      type: Boolean,
      default: false,
    },

    /*
    |--------------------------------------------------------------------------
    | Automatic Logout Time
    |--------------------------------------------------------------------------
    | checkIn + 10 hours
    |--------------------------------------------------------------------------
    */

    autoLogoutAt: {
      type: Date,
      default: null,
    },
  },
  {
    _id: false,
  }
);

/*
|--------------------------------------------------------------------------
| Attendance Schema
|--------------------------------------------------------------------------
*/

const AttendanceSchema = new Schema(
  {
    /*
    |--------------------------------------------------------------------------
    | Employee
    |--------------------------------------------------------------------------
    */

    employee: {
      type: Types.ObjectId,
      ref: 'User',
      required: true,
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Attendance Date
    |--------------------------------------------------------------------------
    | One attendance document per employee per day.
    |--------------------------------------------------------------------------
    */

    date: {
      type: Date,
      required: true,
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | AM Session
    |--------------------------------------------------------------------------
    */

    am: {
      type: SessionSchema,
      default: () => ({}),
    },

    /*
    |--------------------------------------------------------------------------
    | PM Session
    |--------------------------------------------------------------------------
    */

    pm: {
      type: SessionSchema,
      default: () => ({}),
    },

    /*
    |--------------------------------------------------------------------------
    | Overall Current Status
    |--------------------------------------------------------------------------
    */

    currentStatus: {
      type: String,
      enum: ['Working', 'On Break', 'Checked Out'],
      default: 'Checked Out',
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Overall Last Activity
    |--------------------------------------------------------------------------
    */

    lastActivityAt: {
      type: Date,
      default: null,
    },

    /*
    |--------------------------------------------------------------------------
    | Total Working Minutes
    |--------------------------------------------------------------------------
    | AM + PM
    |--------------------------------------------------------------------------
    */

    workingMinutes: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Total Break Minutes
    |--------------------------------------------------------------------------
    | AM + PM
    |--------------------------------------------------------------------------
    */

    breakMinutes: {
      type: Number,
      default: 0,
      min: 0,
    },

    /*
    |--------------------------------------------------------------------------
    | Attendance Status
    |--------------------------------------------------------------------------
    */

    status: {
      type: String,
      enum: ['Present', 'Absent', 'Half Day', 'Leave', 'Holiday', 'Weekly Off'],
      default: 'Absent',
      index: true,
    },

    /*
    |--------------------------------------------------------------------------
    | Attendance Approval
    |--------------------------------------------------------------------------
    */

    approvedBy: {
      type: Types.ObjectId,
      ref: 'User',
      default: null,
    },

    approvedAt: {
      type: Date,
      default: null,
    },

    /*
    |--------------------------------------------------------------------------
    | Audit
    |--------------------------------------------------------------------------
    */

    createdBy: {
      type: Types.ObjectId,
      ref: 'User',
      default: null,
    },

    updatedBy: {
      type: Types.ObjectId,
      ref: 'User',
      default: null,
    },
  },
  {
    timestamps: true,
  }
);

/*
|--------------------------------------------------------------------------
| One Attendance Record Per Employee Per Day
|--------------------------------------------------------------------------
*/

AttendanceSchema.index(
  {
    employee: 1,
    date: 1,
  },
  {
    unique: true,
  }
);

/*
|--------------------------------------------------------------------------
| Employee Attendance Queries
|--------------------------------------------------------------------------
*/

AttendanceSchema.index({
  employee: 1,
  status: 1,
});

AttendanceSchema.index({
  employee: 1,
  currentStatus: 1,
});

/*
|--------------------------------------------------------------------------
| AM Queries
|--------------------------------------------------------------------------
*/

AttendanceSchema.index({
  employee: 1,
  'am.checkIn': 1,
});

AttendanceSchema.index({
  employee: 1,
  'am.checkOut': 1,
});

AttendanceSchema.index({
  employee: 1,
  'am.currentStatus': 1,
});

AttendanceSchema.index({
  employee: 1,
  'am.autoLogoutAt': 1,
});

/*
|--------------------------------------------------------------------------
| PM Queries
|--------------------------------------------------------------------------
*/

AttendanceSchema.index({
  employee: 1,
  'pm.checkIn': 1,
});

AttendanceSchema.index({
  employee: 1,
  'pm.checkOut': 1,
});

AttendanceSchema.index({
  employee: 1,
  'pm.currentStatus': 1,
});

AttendanceSchema.index({
  employee: 1,
  'pm.autoLogoutAt': 1,
});

/*
|--------------------------------------------------------------------------
| Audit Queries
|--------------------------------------------------------------------------
*/

AttendanceSchema.index({
  createdBy: 1,
});

AttendanceSchema.index({
  updatedBy: 1,
});

/*
|--------------------------------------------------------------------------
| Model
|--------------------------------------------------------------------------
*/

export default models.Attendance || model('Attendance', AttendanceSchema);
